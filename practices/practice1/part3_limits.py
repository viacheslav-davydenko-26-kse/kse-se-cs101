# --- службовий блок, його чіпати не треба ---------------------------------
lines = []


def show(*args):
    text = " ".join(str(a) for a in args)
    print(text)
    lines.append(text)
# --------------------------------------------------------------------------


show("=== Дослід 1. Дробові числа ===")
show("0.1 + 0.2 дорівнює", 0.1 + 0.2)
show("Чи дорівнює це рівно 0.3?", 0.1 + 0.2 == 0.3)


show("")
show("=== Дослід 2. Межа точності цілих у float ===")
# 2 ** 53 — це межа, за якою тип float перестає розрізняти сусідні цілі числа.
n = 2 ** 53
show("Ціле 2**53 дорівнює", n)
show("Ціле 2**53 + 1 дорівнює", n + 1)
show("А ось ті самі числа як float:", float(n), "і", float(n + 1))
show("float(2**53) == float(2**53 + 1)?", float(n) == float(n + 1))


show("")
show("=== Дослід 3. Один байт і переповнення ===")
# У Python ціле число росте необмежено. Справжній байт так не вміє.
# Операція & 0xFF залишає від числа тільки молодші вісім бітів —
# тобто поводиться так, як поводився б справжній однобайтовий регістр.
show("255 + 1 у звичайному Python:", 255 + 1)
show("255 + 1 у межах одного байта:", (255 + 1) & 0xFF)
show("Байтовий запис числа -1 у доповнювальному коді:", bin(-1 & 0xFF)[2:])
show("Байтовий запис числа -10 у доповнювальному коді:", bin(-10 & 0xFF)[2:])
show("Перевірка: 10 + (-10) у межах байта дорівнює", (10 + (-10 & 0xFF)) & 0xFF)


show("")
show("=== Дослід 4. Найменша помітна різниця ===")
# Ділимо x навпіл доти, доки 1.0 + x ще відрізняється від 1.0.
x = 1.0
while 1.0 + x / 2.0 > 1.0:
    x = x / 2.0
show("Найменше x, за якого 1.0 + x все ще більше за 1.0:", x)


