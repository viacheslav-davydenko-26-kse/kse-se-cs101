def to_binary(n):
    """Перетворює невід'ємне ціле число n на рядок із його двійковим записом.

    Ця функція вже написана — вона ваш зразок. Розберіть її в методичці.
    """
    if n == 0:
        return "0"
    result = ""
    while n > 0:
        result = str(n % 2) + result
        n = n // 2
    return result


def from_binary(s):
    """Перетворює рядок із двійковим записом на звичайне ціле число.

    ВПРАВА 1. Напишіть тіло цієї функції.

    Ідея — та сама позиційна, що й у лекції, але в зворотний бік.
    Заведіть змінну result = 0 і пройдіть рядок s зліва направо:
    на кожному кроці старе значення множиться на 2, а до нього додається
    поточна цифра. Щоб перебрати символи рядка, пишуть:  for c in s:
    Символ "1" перетворюється на число одиниця через int(c).
    """
    BASE = 2
    if n == "0":
        return 0
    result = 0
    for c in s:
        result = result * BASE + int(c)
    return result


def to_hex(n):
    """Перетворює невід'ємне ціле n на рядок із шістнадцятковим записом.

    ВПРАВА 2. Напишіть тіло цієї функції.

    Робиться так само, як to_binary, але ділити треба на 16, а не на 2.
    Одна складність: остача може бути від 0 до 15, а цифр у нас лише десять.
    Тому беріть символ із готового рядка DIGITS за номером остачі:
    DIGITS[0] це "0", DIGITS[10] це "A", DIGITS[15] це "F".

    Перш ніж вважати функцію готовою, перевірте її на n = 0 — самоперевірка
    починається саме з цього числа. Підказка, де шукати відповідь: подивіться
    ще раз на перші два рядки to_binary.
    """
    # Приберіть рядок нижче і напишіть свій код.
    DIGITS = "0123456789ABCDEF"
    BASE = 16
    if n == 0:
        return "0"
    result = ""
    while n > 0:
        result = DIGITS[(n % BASE)] + result
        n = n // BASE
    return result


# === Самоперевірка ========================================================
# Тут ми порівнюємо свої функції з вбудованими на всіх числах від 0 до 999.
# bin(5) дає рядок "0b101", тому [2:] відкидає перші два символи.

show("=== Самоперевірка ===")

errors = 0

for n in range(1000):
    if to_binary(n) != bin(n)[2:]:
        show("to_binary помилилася на числі", n)
        errors = errors + 1
        break

for n in range(1000):
    if from_binary(bin(n)[2:]) != n:
        show("from_binary помилилася на числі", n)
        errors = errors + 1
        break

for n in range(1000):
    if to_hex(n) != hex(n)[2:].upper():
        show("to_hex помилилася на числі", n)
        errors = errors + 1
        break

if errors == 0:
    show("Усі три функції збіглися з вбудованими на числах від 0 до 999.")
else:
    show("Кількість функцій із помилками:", errors)


