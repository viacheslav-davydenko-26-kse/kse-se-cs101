# Частина 1. Паспорт машини.
# Цей скрипт запитує у Python те, що він може дізнатися про ваш комп'ютер сам.
# Запустіть його, а потім виконайте дві вправи внизу.

import os
import platform
import shutil
import struct

# --- службовий блок, його чіпати не треба ---------------------------------
lines = []


def show(*args):
    """Друкує текст на екран і водночас запам'ятовує його для файлу."""
    text = " ".join(str(a) for a in args)
    print(text)
    lines.append(text)
# --------------------------------------------------------------------------


show("=== Що Python знає про цю машину ===")

show("Операційна система:", platform.system(), platform.release())

# platform.machine() повертає назву архітектури: AMD64 / x86_64 — це сімейство
# x86-64 з лекції, а arm64 / aarch64 — це ARM.
show("Архітектура:", platform.machine())

show("Назва процесора:", platform.processor() or "(система не повідомила)")

# struct.calcsize("P") — це розмір адреси пам'яті в байтах.
# Помноживши на 8, дістаємо розрядність у бітах — те саме машинне слово з лекції.
show("Розрядність Python:", struct.calcsize("P") * 8, "біт")


# === ВПРАВА 1 =============================================================
# Надрукуйте кількість логічних процесорів.
# Функція os.cpu_count() повертає це число.
# Зробіть це через show(), а не print(), інакше рядок не потрапить у файл.
# Зразок для наслідування — рядок про операційну систему вище.
#
# Ваш код:
show("Кількість логічних процесорів:", os.cpu_count())

# === ВПРАВА 2 =============================================================
# Надрукуйте обсяг диска, на якому лежить ця робота, у гігабайтах.
# Підпишіть рядок саме так: "Обсяг диска з цією роботою, ГБ:"
#
# shutil.disk_usage("/") повертає результат, у якого є поле .total у байтах.
# Щоб дістати байти, пишуть: shutil.disk_usage("/").total
# Один гігабайт — це 1024 ** 3 байтів.
# Ділення в Python — це /, але воно дасть довгий дробовий хвіст
# (476.8372802734375). Щоб у файлі було охайне ціле число гігабайтів,
# беріть цілочисельне ділення //
#
# Увага, тонкість. На Windows "/" означає не «системний диск», а корінь того
# диска, з якого запущено скрипт. Якщо ви розпакували роботу на D:, то й
# обсяг буде для D:, а не для C:. Тому це число може не збігтися з тим, що
# ви впишете у «Паспорт машини» — там ідеться саме про системний диск.
# На macOS і Linux "/" — це завжди корінь файлової системи.
#
# Ваш код:
GIGA_BYTE_SIZE = 1024 ** 3
show("Обсяг диска з цією роботою, ГБ:", shutil.disk_usage("/").total // GIGA_BYTE_SIZE)

# --- збереження результату, чіпати не треба -------------------------------
with open("part1_output.txt", "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print()
print("Готово. Результат збережено у файл part1_output.txt")
