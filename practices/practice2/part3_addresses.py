def ip_to_int(s):
    """Перетворює рядок-адресу "192.168.0.1" на одне ціле число.

    Ця функція вже написана — вона ваш зразок. Розберіть її в методичці.

    Адреса ділиться крапками на чотири октети. Найлівіший октет — найстарший:
    його вага 256**3, наступного 256**2, тоді 256, і найправіший — одиниці.
    Це та сама позиційна ідея, що й у десятковій системі, тільки основа 256.
    """
    a, b, c, d = s.split(".")
    return int(a) * 256**3 + int(b) * 256**2 + int(c) * 256 + int(d)


def int_to_ip(n):
    """Перетворює ціле число назад на рядок-адресу "192.168.0.1".

    ВПРАВА 1. Напишіть тіло цієї функції.

    Це обернена дія до ip_to_int, як to_binary навпаки. Кожен октет — це
    остача від ділення на 256, а сама адреса читається справа наліво:
        d = n % 256; n = n // 256   -> найправіший октет
    повторіть чотири рази, збережіть октети й з'єднайте їх крапками.
    Октети йдуть від старшого до молодшого, тож стежте за порядком.
    Рядок із чисел через крапку зручно зібрати так:
        ".".join(str(x) for x in [a, b, c, d])
    Перевірте себе: int_to_ip(ip_to_int("8.8.8.8")) має дати "8.8.8.8".
    """
    d = n % 256; n = n // 256 
    c = n % 256; n = n // 256 
    b = n % 256; n = n // 256 
    a = n % 256; n = n // 256 

    return ".".join(str(x) for x in [a, b, c, d])


def is_valid_ipv4(s):
    """Повертає True, якщо s — коректна IPv4-адреса, інакше False.

    ВПРАВА 2. Напишіть тіло цієї функції.

    Коректна адреса — це рівно чотири частини через крапку, і кожна з них —
    ціле число від 0 до 255 (бо це один байт). Перевірте:
    1. s.split(".") дає РІВНО чотири частини (len(...) == 4).
    2. кожна частина складається лише з цифр (у рядка є метод .isdigit()).
    3. число цієї частини не більше за 255 (і не менше за 0).
    Якщо хоч одна умова не виконана — поверніть False; якщо всі виконані —
    True. Приклади: "1.2.3.4" -> True; "256.0.0.1" -> False (256 не влазить
    у байт); "1.2.3" -> False (замало частин); "a.b.c.d" -> False.
    """
    octets = s.split(".")
    if len(octets) != 4:
        return False

    for octet in octets:
        if not octet.isdigit():
            return False

        if int(octet) > 255 or int(octet) < 0:
            return False

    return True

