# Частина 1. DNS: як ім'я сайту перетворюється на адресу.
#
# Цей скрипт бере кілька доменних імен і питає в системи, яка IP-адреса за
# ними стоїть. Це саме те, що робить браузер щоразу перед відкриттям сайту.
# Запустіть скрипт, а потім виконайте вправу внизу.
#
# Для цієї частини потрібен інтернет. Якщо мережі немає, скрипт не зламається —
# він напише "мережа недоступна" і все одно збереже файл; але тоді ви
# втратите бали за цю частину, тож зробіть її там, де є зв'язок.

import socket

# --- службовий блок, його чіпати не треба ---------------------------------
lines = []


def show(*args):
    """Друкує текст на екран і водночас запам'ятовує його для файлу."""
    text = " ".join(str(a) for a in args)
    print(text)
    lines.append(text)


def resolve(host):
    """Повертає IP-адресу для доменного імені або текст помилки.

    socket.gethostbyname робить рівно те, що DNS у лекції: за іменем
    повертає адресу. Помилку (немає мережі, немає такого домену) ми
    перехоплюємо, щоб скрипт не впав, а чесно про неї повідомив.
    """
    try:
        return socket.gethostbyname(host)
    except OSError as e:
        return "не вдалося (%s)" % e.__class__.__name__
# --------------------------------------------------------------------------


show("=== Ім'я -> адреса (DNS) ===")

for host in ["example.com", "www.google.com", "kse.ua", "uk.wikipedia.org"]:
    show(host, "->", resolve(host))


show("")
show("=== Та сама назва — не завжди та сама адреса ===")
# Великі сайти живуть на багатьох серверах, тож те саме ім'я може давати
# різні адреси. getaddrinfo повертає список усіх адрес, які знає система.
try:
    infos = socket.getaddrinfo("www.google.com", 80, socket.AF_INET)
    addrs = sorted({info[4][0] for info in infos})
    show("www.google.com має адрес:", len(addrs))
    for a in addrs:
        show("  ", a)
except OSError as e:
    show("мережа недоступна:", e.__class__.__name__)


show("")
show("=== Хто ви в мережі ===")
# Ім'я вашого комп'ютера в мережі — його теж видно через socket.
show("Ім'я цього комп'ютера:", socket.gethostname())


